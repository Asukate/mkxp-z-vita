#!/usr/bin/env python3
"""Regenerate src/display/core-font-vdmx.h from the Windows core fonts (needs fontTools).
usage: gen-core-font-vdmx.py ARIAL_TTF TIMES_TTF COURIER_TTF > src/display/core-font-vdmx.h"""
import sys
from fontTools.ttLib import TTFont

print("""/* VDMX height tables (1:1 aspect ratio group, ppem 8-255) of the Windows core fonts that the
 * bundled Liberation fonts stand in for. Liberation keeps their advance widths but has no VDMX,
 * so without these a font size maps to a different pixel size than on Windows (Arial size 22:
 * Windows 19 ppem, linear scaling 20), and text runs about 5% wider than the game expects.
 * Each entry is {yMax, yMin} at ppem = index + VDMX_FIRST_PPEM. Generated by
 * scripts/gen-core-font-vdmx.py from Arial.ttf, Times.ttf and cour.ttf. */
#pragma once
#include <cstdint>

#define VDMX_FIRST_PPEM 8
#define VDMX_LAST_PPEM 255
""")
for name, path in zip(["Arial", "TimesNewRoman", "CourierNew"], sys.argv[1:4]):
    g = TTFont(path)['VDMX'].groups[0]
    vals = [g[k] for k in range(8, 256)]
    print(f"static const int16_t vdmx{name}[248][2] = {{")
    for i in range(0, 248, 8):
        print("    " + ", ".join("{%d, %d}" % v for v in vals[i:i + 8]) + ",")
    print("};\n")
