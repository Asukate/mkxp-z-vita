#!/usr/bin/env python3
"""Generate src/display/core-font-widths.h: the advance widths Windows GDI gives Arial and
Times New Roman (regular) for each ppem, the widths RGSS measures and places text with.
The bundled Liberation stand-ins have the same design widths but no hdmx table and other
hinting, so at small sizes 10-20% of their letters round to a different whole pixel and
lines drift several pixels from what the game was made with (Mysta's Vore RPG, Arial 22).

Input: a TSV dumped on Windows 11 with GetCharWidth32W for lfHeight = -ppem
(face, ppem, actual face, em, widths...) and the codepoint list it used.
usage: gen-core-font-widths.py charwidths.tsv charwidths.cps.txt > src/display/core-font-widths.h
"""
import sys

tsv, cps_file = sys.argv[1:3]
raw = open(cps_file, 'rb').read()
text = raw.decode('utf-16') if raw[:2] == b'\xff\xfe' else raw.decode()
cps = [int(x) for x in text.split(':', 1)[1].split(',')]
rows = {}
for line in open(tsv):
    p = line.rstrip('\n').split('\t')
    if p[2] != p[0] or int(p[3]) != int(p[1]):
        sys.exit(f'unexpected face/em: {p[:4]}')
    rows[(p[0], int(p[1]))] = [int(x) for x in p[4:]]
ppems = sorted({k[1] for k in rows})
first, last = ppems[0], ppems[-1]
assert ppems == list(range(first, last + 1))
assert cps[:224] == list(range(32, 256))


def table(name, face):
    out = [f'static const uint8_t {name}[{len(ppems)}][{len(cps)}] = {{']
    for ppem in ppems:
        w = rows[(face, ppem)]
        # C1 controls have no glyph: 0 = keep the font's own advance.
        w = [0 if 0x7F <= c <= 0x9F else min(v, 255) for c, v in zip(cps, w)]
        out.append('    {' + ','.join(map(str, w)) + '},')
    out.append('};')
    return '\n'.join(out)


print(f'''/* Advance widths Windows GDI gives Arial and Times New Roman (regular) at ppem
 * CW_FIRST_PPEM..CW_LAST_PPEM, for the codepoints in cwCodepoints (32-255, then a few
 * punctuation marks). The bundled Liberation fonts stand in for them with the same design
 * widths but other hinting, so without these a line drifts a few pixels from Windows.
 * Courier New needs none: its widths equal Liberation Mono's. 0 = keep the font's advance.
 * Generated by scripts/gen-core-font-widths.py from a GetCharWidth32W dump on Windows 11. */
#pragma once
#include <cstdint>

#define CW_FIRST_PPEM {first}
#define CW_LAST_PPEM {last}
#define CW_CODEPOINTS {len(cps)}

static const uint16_t cwCodepoints[CW_CODEPOINTS] = {{{','.join(map(str, cps))}}};
''')
print(table('cwArial', 'Arial'))
print()
print(table('cwTimesNewRoman', 'Times New Roman'))
