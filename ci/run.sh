#!/usr/bin/env bash
# The same source checks, clean bootstrap, compile, and packaging run in CI and locally.
set -euo pipefail
PROFILE="${1:-real-vita}"
WS="${2:-/work}"
JOBS="${JOBS:-4}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
git config --global --add safe.directory "$ROOT"
mkdir -p "$WS/logs"
python3 ci/check-source.py 2>&1 | tee "$WS/logs/source.log"
python3 tests/vita-release.py 2>&1 | tee "$WS/logs/release-boundary.log"
python3 tests/ruby-standby.py 2>&1 | tee "$WS/logs/ruby-standby.log"
python3 tests/ruby-localtime.py 2>&1 | tee "$WS/logs/ruby-localtime.log"
python3 tests/ruby-fiber.py --scratch "$WS/test-scratch" 2>&1 | tee "$WS/logs/ruby-fiber.log"
python3 tests/ruby-marshal-load.py --scratch "$WS/test-scratch" 2>&1 | tee "$WS/logs/ruby-marshal-load.log"
ruby tests/ruby-marshal-load.rb 2>&1 | tee -a "$WS/logs/ruby-marshal-load.log"
python3 tests/runtime-log.py 2>&1 | tee "$WS/logs/runtime-log.log"
python3 tests/archive-resume.py 2>&1 | tee "$WS/logs/archive-resume.log"
python3 tests/vitagl-finish.py 2>&1 | tee "$WS/logs/vitagl-finish.log"
c++ -std=c++14 -O2 -I src tests/vita-controls.cpp -o "$WS/vita-controls-tests"
"$WS/vita-controls-tests" 2>&1 | tee "$WS/logs/vita-controls.log"
c++ -std=c++14 -O2 -I src $(pkg-config --cflags sdl2) tests/vita-keyboard.cpp -o "$WS/vita-keyboard-tests"
"$WS/vita-keyboard-tests" 2>&1 | tee "$WS/logs/vita-keyboard.log"
c++ -std=c++14 -O2 -I src tests/vita-pad-replay.cpp -o "$WS/vita-pad-replay-tests"
"$WS/vita-pad-replay-tests" 2>&1 | tee "$WS/logs/vita-pad-replay.log"
c++ -std=c++14 -O2 -I src tests/fast-forward.cpp -o "$WS/fast-forward-tests"
"$WS/fast-forward-tests" 2>&1 | tee "$WS/logs/fast-forward.log"
c++ -std=c++14 -O2 -I src tests/win32-text.cpp -o "$WS/win32-text-tests"
"$WS/win32-text-tests" 2>&1 | tee "$WS/logs/win32-text.log"
c++ -std=c++14 -O2 -I src tests/win32-appdata.cpp -o "$WS/win32-appdata-tests"
APPDATA_SCRATCH="$(mktemp -d "$WS/win32-appdata.XXXXXX")"
(cd "$APPDATA_SCRATCH" && "$WS/win32-appdata-tests") 2>&1 | tee "$WS/logs/win32-appdata.log"
rm -rf -- "$APPDATA_SCRATCH"
ruby tests/vita-controls-overlay.rb 2>&1 | tee "$WS/logs/vita-controls-overlay.log"
ruby tests/legacy-ruby-compat.rb 2>&1 | tee "$WS/logs/legacy-ruby-compat.log"
ruby tests/vxace-map-speedups.rb 2>&1 | tee "$WS/logs/vxace-map-speedups.log"
ruby tests/native-events-cache.rb 2>&1 | tee "$WS/logs/native-events-cache.log"
ruby tests/safe-save.rb 2>&1 | tee "$WS/logs/safe-save.log"
ruby tests/legacy-regexp.rb 2>&1 | tee "$WS/logs/legacy-regexp.log"
ruby tests/rgss-extensions.rb 2>&1 | tee "$WS/logs/rgss-extensions.log"
ruby tests/sprite-fastpath.rb 2>&1 | tee "$WS/logs/sprite-fastpath.log"
./scripts/test-midi-host.sh "$WS/host-midi" 2>&1 | tee "$WS/logs/midi.log"
python3 tests/openal-empty-buffer.py 2>&1 | tee "$WS/logs/openal-empty-buffer.log"
python3 tests/performance-metrics.py 2>&1 | tee "$WS/logs/performance-metrics.log"
python3 tests/bitmap-cpu-compose.py 2>&1 | tee "$WS/logs/bitmap-cpu-compose.log"
python3 tests/bitmap-window-regions.py 2>&1 | tee "$WS/logs/bitmap-window-regions.log"
python3 tests/bitmap-memory.py 2>&1 | tee "$WS/logs/bitmap-memory.log"
python3 tests/image-decoder.py 2>&1 | tee "$WS/logs/image-decoder.log"
python3 tests/image-bands.py 2>&1 | tee "$WS/logs/image-bands.log"
python3 tests/image-jpeg-colors.py 2>&1 | tee "$WS/logs/image-jpeg-colors.log"
python3 tests/image-streaming.py 2>&1 | tee "$WS/logs/image-streaming.log"
python3 tests/image-sparse-decoding.py 2>&1 | tee "$WS/logs/image-sparse-decoding.log"
c++ -std=c++17 -fsanitize=address,undefined -g -I src tests/image-crop.cpp -o "$WS/image-crop-tests"
"$WS/image-crop-tests" 2>&1 | tee "$WS/logs/image-crop.log"
python3 tests/image-crop-render.py 2>&1 | tee "$WS/logs/image-crop-render.log"
python3 tests/bitmap-direct-pixel.py 2>&1 | tee "$WS/logs/bitmap-direct-pixel.log"
python3 tests/bitmap-mapped-clear.py 2>&1 | tee "$WS/logs/bitmap-mapped-clear.log"
python3 tests/tilemap-empty-autotile.py 2>&1 | tee "$WS/logs/tilemap-empty-autotile.log"
python3 tests/font-vdmx.py 2>&1 | tee "$WS/logs/font-vdmx.log"
./scripts/bootstrap-vita.sh --ws "$WS" --profile "$PROFILE" -j "$JOBS" 2>&1 | tee "$WS/logs/bootstrap.log"
python3 tests/pixel-transfer.py "$WS/src/vitaGL" 2>&1 | tee "$WS/logs/pixel-transfer.log"
./scripts/build-vita.sh --ws "$WS" --profile "$PROFILE" -j "$JOBS" 2>&1 | tee "$WS/logs/build.log"
./scripts/package-launcher.sh --ws "$WS" --profile "$PROFILE" 2>&1 | tee "$WS/logs/package.log"
cp "$WS"/*state.json "$WS/bootstrap-manifest.txt" "$WS/packages/"
(cd "$WS/packages" && sha256sum *.vpk *state.json bootstrap-manifest.txt > SHA256SUMS)
